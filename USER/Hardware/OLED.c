/**
 * @brief  显示一个有符号整数
 * @param  x:    起始列位置
 * @param  y:    页位置
 * @param  num:  要显示的数字 (可为负数)
 * @param  len:  显示的总位数 (高位不够用空格补齐, 用于对齐)
 *
 *  例: OLED_ShowNum(0, 0, -42, 5) → 显示 "  -42"
 *      OLED_ShowNum(0, 0, 123, 4)  → 显示 " 123"
 */
void OLED_ShowNum(uint8_t x, uint8_t y, int32_t num, uint8_t len)
{
    char buf[12];   /* 最多显示 11 位 (含符号) + 1 个 '\0' */
    uint8_t i;

    /* 处理负数 */
    if (num < 0)
    {
        buf[len] = '\0';        /* 先放字符串结尾 */
        num = -num;             /* 取绝对值 */

        /* 从右往左逐位填入数字 */
        for (i = len - 1; ; i--)
        {
            buf[i] = '0' + (num % 10);  /* 取个位数转为字符 */
            num /= 10;                   /* 去掉已处理的位 */

            if (num == 0)
                break;
            if (i == 0) break;           /* 防止溢出 */
        }

        /* 前导空格 */
        while (i > 1) { buf[--i] = ' '; }

        /* 负号 */
        buf[0] = '-';
    }
    else
    {
        buf[len] = '\0';
        for (i = len - 1; ; i--)
        {
            buf[i] = '0' + (num % 10);
            num /= 10;
            if (num == 0)
                break;
            if (i == 0) break;
        }
        /* 前导空格 */
        while (i > 0) { buf[--i] = ' '; }
    }

    OLED_ShowString(x, y, buf);
}

/**
 * @brief  显示一个浮点数 (保留指定小数位数)
 * @param  x:      起始列位置
 * @param  y:      页位置
 * @param  num:    要显示的浮点数
 * @param  intLen: 整数部分显示位数
 * @param  decLen: 小数部分显示位数
 *
 *  例: OLED_ShowFloat(0, 0, 3.14, 2, 2) → 显示 " 3.14"
 *
 *  处理负数的方法:
 *    如果 num < 0, 先输出负号, 然后对绝对值进行转换.
 */
void OLED_ShowFloat(uint8_t x, uint8_t y, float num, uint8_t intLen, uint8_t decLen)
{
    uint32_t intPart, decPart;
    uint8_t negative = 0;

    /* 处理负数 */
    if (num < 0)
    {
        negative = 1;
        num = -num;
    }

    /* 分离整数和小数部分 */
    intPart = (uint32_t)num;                              /* 整数部分 */
    float frac = num - (float)intPart;                    /* 小数部分 (0.xxx) */

    /* 将小数部分转为整数 (例: frac=0.14, decLen=2 → 0.14*100=14) */
    {
        uint8_t i;
        for (i = 0; i < decLen; i++)
            frac *= 10;
    }
    decPart = (uint32_t)(frac + 0.5f);                    /* +0.5 用于四舍五入 */

    /*
     * 手动构建字符串, 格式: [负号][空格...整数][小数点][小数]
     * 这里用 OLED_ShowChar 逐字输出更灵活
     */
    uint8_t buf[12];
    uint8_t pos = 0;

    /* 先在同一行拼好字符串, 再一次性用 ShowString 显示 */

    /* --- 整数部分 (右对齐, 前导空格) --- */
    {
        uint8_t intBuf[6];
        uint8_t intCount = 0;

        if (intPart == 0)
        {
            intBuf[intCount++] = 0;
        }
        else
        {
            while (intPart > 0)
            {
                intBuf[intCount++] = intPart % 10;
                intPart /= 10;
            }
        }

        /* 前导空格 */
        while (intCount < intLen)
            buf[pos++] = ' ';

        /* 如果有负号且还有空间 */
        if (negative && pos > 0)
        {
            /* 负号放在数字前面紧挨着 */
            buf[pos - 1] = '-';
        }
        else if (negative)
        {
            buf[pos++] = '-';
        }

        /* 倒序填入整数数字 (因为 intBuf 存的是低位在前) */
        {
            int8_t j;
            for (j = intCount - 1; j >= 0; j--)
                buf[pos++] = '0' + intBuf[j];
        }
    }

    /* --- 小数点 --- */
    buf[pos++] = '.';

    /* --- 小数部分 --- */
    {
        uint8_t decBuf[6];
        uint8_t decCount = 0;

        if (decPart == 0)
        {
            decBuf[decCount++] = 0;
        }
        else
        {
            while (decPart > 0)
            {
                decBuf[decCount++] = decPart % 10;
                decPart /= 10;
            }
        }

        /* 小数部分右对齐 (高位补零, 区别于整数的前导空格) */
        while (decCount < decLen)
            decBuf[decCount++] = 0;

        /* 倒序填入 */
        {
            int8_t j;
            for (j = decCount - 1; j >= 0; j--)
                buf[pos++] = '0' + decBuf[j];
        }
    }

    buf[pos] = '\0';

    /* 一次性显示整个字符串 */
    OLED_ShowString(x, y, (const char *)buf);
}
