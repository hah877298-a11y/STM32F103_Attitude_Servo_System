#ifndef __SERVO_H
#define __SERVO_H

#include "stm32f10x.h"

/* ============================================================
 *              SG90 舵 机 PWM 驱 动 头 文 件
 * ============================================================
 *
 *  硬件连接:
 *    信号线 → PA0 (TIM2_CH1)
 *    电源线 → 外部 5V (不要从 STM32 的 3.3V 取电!)
 *    GND   → 与 STM32 共地
 *
 *  SG90 舵机参数:
 *    工作电压:   4.8V ~ 6.0V (推荐 5V)
 *    控制信号:   50Hz PWM (周期 20ms)
 *    脉冲范围:   0.5ms ~ 2.5ms
 *    角度范围:   0° ~ 180° (部分舵机只能 0°~90°)
 *    堵转电流:   ~750mA (启动瞬间可能更大!)
 *
 *  PWM 与角度的对应关系:
 *    ┌──────────┬──────────┬──────────┐
 *    │  角度    │  脉宽    │  CCR值   │
 *    │          │          │ (1MHz)   │
 *    ├──────────┼──────────┼──────────┤
 *    │    0°    │  0.5ms   │   500    │
 *    │   45°    │  1.0ms   │  1000    │
 *    │   90°    │  1.5ms   │  1500    │
 *    │  135°    │  2.0ms   │  2000    │
 *    │  180°    │  2.5ms   │  2500    │
 *    └──────────┴──────────┴──────────┘
 *
 *  定时器配置:
 *    TIM2 挂在 APB1 总线 (最大 72MHz, APB1 预分频器 ≠1 时 ×2)
 *    PSC = 72-1 = 71  → 计数器时钟 = 1MHz (1µs 精度)
 *    ARR = 20000-1    → 周期 20ms (50Hz)
 *
 *  ★ 为什么舵机必须用独立的 5V 供电?
 *    STM32 的 3.3V 引脚最大输出电流约 150mA,
 *    而 SG90 堵转电流可达 750mA 以上.
 *    如果从 3.3V 取电 → 电压被拉低 → STM32 复位!
 *    如果从开发板的 5V 引脚取电 → USB 口最大 500mA,
 *    舵机堵转 + OLED + MPU6050 → 也可能复位!
 *
 *  推荐供电方案:
 *    外接 5V/2A 电源适配器, 或者用两个 USB 口分别供电.
 * ============================================================
 */

/* ========== 舵 机 角 度 范 围 ========== */
#define SERVO_MIN_ANGLE     0       /* 最小角度 (°) */
#define SERVO_MAX_ANGLE     180     /* 最大角度 (°) */

/* ========== PWM 脉 冲 范 围 (CCR 值, 1MHz 时钟) ========== */
#define SERVO_MIN_PULSE     500     /* 0.5ms → 0° */
#define SERVO_MAX_PULSE     2500    /* 2.5ms → 180° */

/* ========== 对 外 接 口 ========== */

void Servo_Init(void);                      /* 初始化 TIM2_CH1 PWM 输出 */
void Servo_SetAngle(int16_t angle);         /* 设置舵机角度 (0~180°) */
void Servo_SetPulse(uint16_t pulse_us);     /* 直接设置脉冲宽度 (µs), 500~2500 */

#endif /* __SERVO_H */
