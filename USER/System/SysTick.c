#include "SysTick.h"

/* ============================================================
 *             SysTick 系 统 节 拍 定 时 器 实 现
 * ============================================================
 *
 *  工作原理 (逐层拆解):
 *
 *  [硬件层] SysTick 定时器
 *    - 24 位倒计数寄存器 (最大值 16777215)
 *    - 计数频率 = 系统时钟 / 分频系数
 *    - 当前值减到 0 时:
 *        ① 产生 SysTick 中断 (如果使能了)
 *        ② 自动从 RELOAD 寄存器加载初值, 继续倒计数
 *    - 这种"自动重装"机制保证定时精度不受中断处理时间影响
 *
 *  [驱动层] 本文件
 *    - 计算 Reload 值, 使定时器每 1ms 中断一次
 *    - 提供 sysTickCounter, 在中断中递增
 *    - 提供 SysTick_Get() 查询"现在几点"
 *
 *  [应用层] main.c
 *    - 在 SysTick_Handler() 中调用 SysTick_IncTick()
 *    - 在 while(1) 中用 if (now - last >= 周期) 实现非阻塞任务调度
 *
 *  为什么用 1ms 中断周期?
 *    - 1ms 对 STM32F103 (72MHz) 来说非常轻松:
 *      每秒 1000 次中断, 每次几十个 CPU 周期,
 *      CPU 占用率 <0.1%, 几乎可以忽略
 *    - 1ms 精度足够我们所有任务:
 *      OLED 刷新(100ms级)、IMU 读取(5ms级)、
 *      串口打印(50ms级)、舵机控制(20ms级)
 *
 *  溢出安全性分析 (面试常考题!):
 *    sysTickCounter 是 uint32_t, 在约 49.7 天后溢出回零.
 *    但我们的计时方法 "now - last >= interval" 因为用了无符号数减法,
 *    在溢出时依然正确:
 *
 *      例: last = 0xFFFFFFF0 (即将溢出前)
 *          now  = 0x0000000F (溢出之后)
 *          now - last = 0x0000000F - 0xFFFFFFF0
 *                   = 0x0000001F  (模运算: 31ms, 正确!)
 *
 *    这是 C 语言无符号整数的模运算特性, 只要延迟不超过 49 天,
 *    计算就永远不会出错.
 * ============================================================
 */

/* 全局毫秒计数器: 每次 SysTick 中断 +1
 *
 * volatile 关键字的作用:
 *   告诉编译器 "这个变量的值可能在任何时刻被中断改变",
 *   禁止编译器将其优化到寄存器中反复读取.
 *   如果不用 volatile, 主循环可能会读到过期的缓存值,
 *   导致任务永远不被触发 (经典的"while 循环优化 bug").
 *
 * static 的作用:
 *   限制变量作用域在本文件内, 外部 .c 文件不能直接访问.
 *   只能通过 SysTick_Get() / SysTick_IncTick() 接口操作,
 *   这是面向对象思想的 C 语言实现——"封装".
 */
static volatile uint32_t sysTickCounter = 0;

/* ============================================================
 *                 初 始 化 SysTick
 * ============================================================
 */
/**
 * @brief  初始化 SysTick 定时器, 每 1ms 产生一次中断
 *
 *  SysTick_Config() 是 CMSIS 提供的标准函数, 做了三件事:
 *    1. 设置 SysTick->LOAD (自动重装值)  = reload_val - 1
 *    2. 设置 SysTick 优先级为最低 (对实时性没要求)
 *    3. 启动定时器 + 使能中断
 *
 *  reload_val 的计算:
 *    SystemCoreClock = 72,000,000 Hz (STM32F103 最大主频)
 *    我们希望每 1ms 中断一次 → 频率 1000Hz
 *    reload_val = 72,000,000 / 1000 = 72,000
 *
 *    意思是: 定时器从 72000 倒数到 0, 恰好是 1ms.
 *
 *  返回值:
 *    0 = 成功
 *    1 = 失败 (reload_val > 0xFFFFFF = 16777215, 但在 72MHz/1000 时不会)
 *
 *  思考: 如果主频不是 72MHz 怎么办?
 *    SystemCoreClock 是一个全局变量, CMSIS 启动文件
 *    (system_stm32f10x.c) 根据时钟配置自动更新它.
 *    所以我们的代码适配任意主频, 不需要硬编码.
 */
void SysTick_Init(void)
{
    if (SysTick_Config(SystemCoreClock / 1000))
    {
        /*
         * SysTick_Config() 返回非 0 表示失败.
         * 理论上 SystemCoreClock/1000 不可能超过 0xFFFFFF,
         * 但加上这个检查是一个好习惯 (防御性编程).
         * 如果真进了这里, 说明 clock 配置有问题, 死循环让开发者发现.
         */
        while (1);
    }

    /*
     * 初始化完成后, SysTick 立即开始工作:
     *   72000 → 71999 → ... → 0 → 中断! → 自动重装 72000 → ...
     *
     * 注意: SysTick 的中断优先级已被 SysTick_Config() 设为最低,
     *        所以它不会打断其他重要的中断服务.
     */
}

/* ============================================================
 *                 获 取 当 前 毫 秒 数
 * ============================================================
 */
/**
 * @brief  返回自 SysTick_Init() 以来的毫秒计数
 *
 *  这是整个非阻塞调度器的核心.
 *  主循环中任何需要"每隔 X 毫秒做一次"的逻辑,
 *  都可以用这个函数配合简单的 if 语句实现.
 *
 *  使用模式:
 *    static uint32_t lastTime = 0;
 *    if (SysTick_Get() - lastTime >= interval) {
 *        lastTime = SysTick_Get();
 *        doSomething();
 *    }
 *
 *  为什么先判断再更新 lastTime?
 *    防止 doSomething() 执行耗时过长导致间隔不准.
 *    如果先更新再执行, 实际间隔 = interval + 执行时间.
 */
uint32_t SysTick_Get(void)
{
    return sysTickCounter;
}

/* ============================================================
 *         递 增 计 数 器 (在 中 断 中 调 用)
 * ============================================================
 */
/**
 * @brief  在 SysTick_Handler 中断服务中调用, 让计数器 +1
 *
 *  这个函数极短 (只有一条语句), 目的是让中断服务程序尽可能快.
 *  中断里做的事情越少, 系统实时性越好.
 *
 *  如果直接把 sysTickCounter 暴露为全局变量,
 *  其他模块可能意外修改它, 导致不可排查的 bug.
 *  封装成函数 = 只允许读取 (SysTick_Get), 只允许在中断里递增 (SysTick_IncTick).
 */
void SysTick_IncTick(void)
{
    sysTickCounter++;
}
